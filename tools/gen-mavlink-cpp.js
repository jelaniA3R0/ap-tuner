// Generates cpp/io/src/mavlink_defs.inc (message layouts, CRC extras and the enums the app uses) from
// src/mavlink/defs.json, so the C++ version speaks exactly the same MAVLink dialect as the JavaScript one.
//   node tools/gen-mavlink-cpp.js
'use strict';
const fs = require('fs');
const path = require('path');
const defs = require('../src/mavlink/defs.json');

const T = { char: 'kChar', int8_t: 'kI8', uint8_t: 'kU8', int16_t: 'kI16', uint16_t: 'kU16', int32_t: 'kI32', uint32_t: 'kU32', float: 'kF32', double: 'kF64', int64_t: 'kI64', uint64_t: 'kU64' };
const q = s => JSON.stringify(s);
const lines = ['// Generated by tools/gen-mavlink-cpp.js from src/mavlink/defs.json: do not edit.', ''];
const ids = Object.keys(defs.messages).map(Number).sort((a, b) => a - b);
for (const id of ids) {
  const m = defs.messages[id];
  lines.push(`static const FieldDef kFields_${id}[] = {` + m.fields.map(f => `{${q(f.name)}, ${T[f.type]}, ${f.len || 0}, ${f.offset}}`).join(', ') + '};');
}
lines.push('', 'static const MsgDef kMessages[] = {');
for (const id of ids) {
  const m = defs.messages[id];
  lines.push(`  {${id}, ${q(m.name)}, ${m.crcExtra}, ${m.length}, kFields_${id}, ${m.fields.length}},`);
}
lines.push('};', '');
for (const e of ['MAV_TYPE', 'COPTER_MODE', 'PLANE_MODE']) {
  const entries = Object.entries(defs.enums[e] || {}).map(([v, n]) => [Number(v), n]).sort((a, b) => a[0] - b[0]);
  lines.push(`static const EnumEntry kEnum_${e}[] = {` + entries.map(([v, n]) => `{${v}, ${q(n)}}`).join(', ') + '};');
}
const out = path.join(__dirname, '..', 'cpp', 'io', 'src', 'mavlink_defs.inc');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${out}: ${ids.length} messages`);
